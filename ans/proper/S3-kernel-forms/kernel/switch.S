# S3 · cooperative context switch (given to students).
# __switch(struct TaskContext *cur /*a0*/, struct TaskContext *next /*a1*/)
# TaskContext layout: ra@0, sp@8, s0..s11 @16..104 (callee-saved only).
# Save current callee-saved regs + ra/sp into *cur, then load them from *next
# and `ret`. Because ra/sp/s0-s11 fully describe a frame, control resumes
# wherever *next last called __switch (or, for a fresh task, at ra=bootstrap).
    .section .text
    .globl __switch
__switch:
    sd   ra,   0(a0)
    sd   sp,   8(a0)
    sd   s0,  16(a0)
    sd   s1,  24(a0)
    sd   s2,  32(a0)
    sd   s3,  40(a0)
    sd   s4,  48(a0)
    sd   s5,  56(a0)
    sd   s6,  64(a0)
    sd   s7,  72(a0)
    sd   s8,  80(a0)
    sd   s9,  88(a0)
    sd   s10, 96(a0)
    sd   s11,104(a0)

    ld   ra,   0(a1)
    ld   sp,   8(a1)
    ld   s0,  16(a1)
    ld   s1,  24(a1)
    ld   s2,  32(a1)
    ld   s3,  40(a1)
    ld   s4,  48(a1)
    ld   s5,  56(a1)
    ld   s6,  64(a1)
    ld   s7,  72(a1)
    ld   s8,  80(a1)
    ld   s9,  88(a1)
    ld   s10, 96(a1)
    ld   s11,104(a1)
    ret
